#!/usr/bin/env python3
"""Project-level status report. Aggregates work items + Cycles +
Modules + Milestones into a single STATUS.md."""

from __future__ import annotations

import argparse
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path.home() / ".claude" / "lib"))
from plane_schema import (
    Cycle,
    Module,
    Milestone,
    Project,
    WorkItem,
    list_project_work_items,
    project_dir,
    resolve_org_repo,
)


STATE_ORDER = ["backlog", "unstarted", "started", "completed",
               "cancelled", "deferred"]
PRIORITY_ORDER = ["urgent", "high", "medium", "low", "none"]
SEVERITY_ORDER = ["critical", "high", "medium", "low", "informational"]


def render_count_table(title: str, counts: Counter, order: list[str]) -> list[str]:
    if not any(counts.values()):
        return []
    out = [f"### {title}", "", "| Bucket | Count |", "|---|---:|"]
    for k in order:
        n = counts.get(k, 0)
        if n:
            out.append(f"| {k} | {n} |")
    # Catch unknown keys
    for k in sorted(counts):
        if k not in order:
            out.append(f"| {k} | {counts[k]} |")
    out.append("")
    return out


def render(project: Project | None, org: str, repo: str,
           items: list[WorkItem], cycles: list[Cycle]) -> str:
    project_name = project.name if project else repo
    ship_target = project.ship_target if project else ""
    project_state = project.state if project else "active"

    lines = [
        f"# {project_name} — Project status",
        "",
        f"_Auto-generated by `/plane-project-status`. Re-run to refresh._",
        "",
        f"- **Workspace:** `{org}`",
        f"- **Project state:** {project_state}",
    ]
    if ship_target:
        lines.append(f"- **Ship target:** {ship_target}")
    lines.append(f"- **Total work items:** {len(items)}")
    lines.append("")

    if not items:
        lines.append("_No work items in the project pool yet. Run an audit or "
                     "create work items manually._")
        return "\n".join(lines)

    state_c = Counter(wi.state for wi in items)
    prio_c = Counter(wi.priority for wi in items)
    sev_c = Counter(wi.audit_severity or "n/a" for wi in items)

    lines.append("## Distribution")
    lines.append("")
    lines += render_count_table("By state", state_c, STATE_ORDER)
    lines += render_count_table("By priority", prio_c, PRIORITY_ORDER)
    lines += render_count_table("By audit severity",
                                Counter({k: v for k, v in sev_c.items() if k != "n/a"}),
                                SEVERITY_ORDER)
    if sev_c.get("n/a"):
        lines.append(f"_{sev_c['n/a']} item(s) have no audit severity "
                     f"(manual / non-audit-origin)._")
        lines.append("")

    # Per-module breakdown
    module_state: dict[str, Counter] = {}
    for wi in items:
        key = wi.module or "(unassigned)"
        module_state.setdefault(key, Counter())[wi.state] += 1
    if module_state:
        lines.append("## By Module")
        lines.append("")
        header = "| Module | " + " | ".join(STATE_ORDER) + " | Total |"
        sep = "|---|" + "---:|" * (len(STATE_ORDER) + 1)
        lines.append(header)
        lines.append(sep)
        for mod_key in sorted(module_state.keys(),
                              key=lambda k: (k == "(unassigned)", k)):
            ctr = module_state[mod_key]
            mod_obj = (Module.load(org, repo, mod_key)
                       if mod_key != "(unassigned)" else None)
            display = mod_obj.name if mod_obj else mod_key
            row_total = sum(ctr.values())
            cells = " | ".join(str(ctr.get(s, 0)) for s in STATE_ORDER)
            lines.append(f"| {display} | {cells} | {row_total} |")
        lines.append("")

    # Per-milestone breakdown
    milestone_state: dict[str, Counter] = {}
    for wi in items:
        key = wi.milestone or "(unassigned)"
        milestone_state.setdefault(key, Counter())[wi.state] += 1
    if any(k != "(unassigned)" for k in milestone_state):
        lines.append("## By Milestone")
        lines.append("")
        lines.append("| Milestone | " + " | ".join(STATE_ORDER) + " | Total |")
        lines.append("|---|" + "---:|" * (len(STATE_ORDER) + 1))
        for m_key in sorted(milestone_state.keys(),
                            key=lambda k: (k == "(unassigned)", k)):
            ctr = milestone_state[m_key]
            m_obj = (Milestone.load(org, repo, m_key)
                     if m_key != "(unassigned)" else None)
            display = m_obj.name if m_obj else m_key
            row_total = sum(ctr.values())
            cells = " | ".join(str(ctr.get(s, 0)) for s in STATE_ORDER)
            lines.append(f"| {display} | {cells} | {row_total} |")
        lines.append("")

    # Cycles
    if cycles:
        active = [c for c in cycles if c.state == "active"]
        lines.append("## Cycles")
        lines.append("")
        lines.append("| Cycle | State | Dates | Items |")
        lines.append("|---|---|---|---:|")
        cycle_counts = Counter(wi.cycle for wi in items if wi.cycle)
        for c in cycles:
            dates = f"{c.start_date or '?'} → {c.end_date or '?'}"
            lines.append(f"| `{c.id}` | {c.state} | {dates} | "
                         f"{cycle_counts.get(c.id, 0)} |")
        lines.append("")
        if active:
            for c in active:
                lines.append(f"_Active Cycle: **{c.name}** (`{c.id}`)._")
                lines.append("")

    # Audit source coverage
    audit_c = Counter(wi.audit_type for wi in items if wi.audit_type)
    if audit_c:
        lines.append("## Audit-source coverage")
        lines.append("")
        lines.append("| Audit type | Items |")
        lines.append("|---|---:|")
        for at, n in sorted(audit_c.items(), key=lambda kv: (-kv[1], kv[0])):
            lines.append(f"| {at} | {n} |")
        lines.append("")

    # Landed
    landed = [wi for wi in items if wi.landed_in]
    if landed:
        landed.sort(key=lambda w: (w.updated or ""), reverse=True)
        lines.append(f"## Recently landed ({len(landed)})")
        lines.append("")
        lines.append("| ID | Commit | Title |")
        lines.append("|---|---|---|")
        for wi in landed[:15]:
            title = wi.title.replace("|", "\\|")[:70]
            lines.append(f"| {wi.id} | `{wi.landed_in}` | {title} |")
        if len(landed) > 15:
            lines.append(f"| _…and {len(landed) - 15} more_ |  |  |")
        lines.append("")

    # Footer
    lines += [
        "---",
        "",
        f"_Source: `{project_dir(org, repo)}`._",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--scope", default=".", help="Project root.")
    ap.add_argument("--stdout", action="store_true",
                    help="Print to stdout instead of writing STATUS.md.")
    args = ap.parse_args()

    project_cwd = Path(args.scope).resolve()
    org, repo = resolve_org_repo(project_cwd)

    items: list[WorkItem] = []
    for p in list_project_work_items(org, repo):
        try:
            items.append(WorkItem.load(p))
        except Exception:
            continue
    cycles = Cycle.list(org, repo)
    project = Project.load(org, repo)

    text = render(project, org, repo, items, cycles)

    if args.stdout:
        print(text)
    else:
        out = project_dir(org, repo) / "STATUS.md"
        out.write_text(text)
        print(f"project: {org}/{repo}")
        print(f"items:   {len(items)}")
        print(f"cycles:  {len(cycles)}")
        print(f"output:  {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
