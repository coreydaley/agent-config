#!/usr/bin/env python3
"""Close out a Cycle. Generates RETRO.md (or RETRO-PREVIEW.md in
dry-run) and flips cycle.state to completed."""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path.home() / ".claude" / "lib"))
from plane_schema import (
    Cycle,
    Project,
    WorkItem,
    list_project_work_items,
    now_iso,
    resolve_org_repo,
)


PRIORITY_ORDER = {"urgent": 0, "high": 1, "medium": 2, "low": 3, "none": 4}


def resolve_cycle(org: str, repo: str, requested: str | None) -> Cycle | None:
    cycles = Cycle.list(org, repo)
    if not cycles:
        return None
    if requested:
        for c in cycles:
            if c.id == requested:
                return c
        return None
    active = [c for c in cycles if c.state == "active"]
    if len(active) == 1:
        return active[0]
    return cycles[-1]


def classify(items: list[WorkItem]) -> dict[str, list[WorkItem]]:
    buckets: dict[str, list[WorkItem]] = {
        "landed": [], "slipped": [], "deferred": [], "cancelled": [],
    }
    for wi in items:
        if wi.state == "completed":
            buckets["landed"].append(wi)
        elif wi.state == "cancelled":
            buckets["cancelled"].append(wi)
        elif wi.state == "deferred":
            buckets["deferred"].append(wi)
        else:
            # backlog, unstarted, started → slipped
            buckets["slipped"].append(wi)
    return buckets


def render(cycle: Cycle, items: list[WorkItem], project: Project | None,
           notes: str, applied: bool) -> str:
    buckets = classify(items)
    project_name = project.name if project else cycle.project
    header = "Cycle close" if applied else "Cycle close PREVIEW (dry-run)"

    lines = [
        f"# {project_name} — {header}: {cycle.name}",
        "",
        f"_Auto-generated by `/plane-cycle-close`._",
        "",
        f"- **Cycle:** `{cycle.id}`",
        f"- **Dates:** {cycle.start_date or '?'} → {cycle.end_date or '?'}",
        f"- **State at close:** {cycle.state} → " +
            ("completed (applied)" if applied else "completed (would set)"),
        f"- **{'Closed' if applied else 'Planned-close'} at:** {now_iso()}",
    ]
    if cycle.goal:
        lines.append(f"- **Goal:** {cycle.goal}")
    if cycle.exit_criteria:
        lines.append("- **Exit criteria:**")
        for ec in cycle.exit_criteria:
            lines.append(f"  - {ec}")
    lines.append("")

    # Summary
    lines.append("## Summary")
    lines.append("")
    lines.append("| Bucket | Count |")
    lines.append("|---|---:|")
    for k in ("landed", "slipped", "deferred", "cancelled"):
        lines.append(f"| {k} | {len(buckets[k])} |")
    lines.append(f"| **total** | **{len(items)}** |")
    lines.append("")

    # Per-bucket details
    def render_bucket(name: str, header_text: str, with_extras: list[str]):
        items_b = sorted(buckets[name],
                         key=lambda w: (PRIORITY_ORDER.get(w.priority, 99), w.id))
        if not items_b:
            return
        lines.append(f"## {header_text} ({len(items_b)})")
        lines.append("")
        cols = ["ID", "Priority", "Title"] + with_extras
        lines.append("| " + " | ".join(cols) + " |")
        lines.append("|" + "---|" * len(cols))
        for wi in items_b:
            title = wi.title.replace("|", "\\|")[:80]
            row = [wi.id, wi.priority, title]
            for col in with_extras:
                if col == "Commit":
                    row.append(f"`{wi.landed_in}`" if wi.landed_in else "—")
                elif col == "State":
                    row.append(wi.state)
                elif col == "Defer to":
                    row.append(wi.deferral_target or "?")
                elif col == "Reason":
                    reason = (wi.deferral_reason or "")[:60].replace("|", "\\|").replace("\n", " ")
                    row.append(reason)
                else:
                    row.append("")
            lines.append("| " + " | ".join(row) + " |")
        lines.append("")

    render_bucket("landed",    "✅ Landed",                ["Commit"])
    render_bucket("slipped",   "⏭️ Slipped (still open)", ["State"])
    render_bucket("deferred",  "⏸ Explicitly deferred",   ["Defer to", "Reason"])
    render_bucket("cancelled", "✖ Cancelled",             [])

    if buckets["slipped"]:
        lines.append("### Slipped items — next steps")
        lines.append("")
        lines.append(
            "Slipped items still point at this Cycle via their `cycle:` "
            "field (audit trail). To move them to a future Cycle:"
        )
        lines.append("")
        lines.append("```")
        lines.append("/plane-cycle-new --name 'Next Cycle' [...]")
        ids = " ".join(f"--id {wi.id}" for wi in buckets["slipped"])
        lines.append(f"/plane-work-item-assign {ids} --cycle <new-cycle-id>")
        lines.append("```")
        lines.append("")

    if notes:
        lines.append("## Retro notes")
        lines.append("")
        lines.append(notes.strip())
        lines.append("")

    if not applied:
        lines += [
            "---",
            "",
            "## Next step",
            "",
            "Re-run with `--apply` to flip the Cycle state to `completed` and "
            "promote this preview to `RETRO.md`:",
            "",
            "```",
            f"python3 scripts/close.py --cycle {cycle.id} --apply",
            "```",
            "",
        ]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--scope", default=".", help="Project root.")
    ap.add_argument("--cycle", help="Cycle id.")
    ap.add_argument("--notes", default="", help="Free-text retro notes.")
    ap.add_argument("--apply", action="store_true",
                    help="Execute. Default is dry-run.")
    args = ap.parse_args()

    project_cwd = Path(args.scope).resolve()
    org, repo = resolve_org_repo(project_cwd)

    cycle = resolve_cycle(org, repo, args.cycle)
    if cycle is None:
        print(f"error: no Cycle{f' with id {args.cycle!r}' if args.cycle else 's'} "
              f"in {org}/{repo}", file=sys.stderr)
        return 1

    if cycle.state in ("completed", "cancelled"):
        print(f"error: cycle {cycle.id} is already {cycle.state} — "
              f"refusing to close a non-active Cycle.", file=sys.stderr)
        return 2

    # Collect items
    items: list[WorkItem] = []
    for p in list_project_work_items(org, repo):
        try:
            wi = WorkItem.load(p)
        except Exception:
            continue
        if wi.cycle == cycle.id:
            items.append(wi)

    project = Project.load(org, repo)
    text = render(cycle, items, project, args.notes, applied=args.apply)

    cycle_dir = Cycle.dir_for(org, repo, cycle.id)
    if args.apply:
        # Flip state, save
        prior_state = cycle.state
        cycle.state = "completed"
        cycle.save()
        # Final RETRO.md
        out = cycle_dir / "RETRO.md"
        out.write_text(text)
        # Clear any prior preview
        preview = cycle_dir / "RETRO-PREVIEW.md"
        if preview.exists():
            preview.unlink()
        print(f"cycle:    {cycle.id} (was {prior_state}, now completed)")
        print(f"output:   {out}")
        b = classify(items)
        print(f"summary:  landed={len(b['landed'])} slipped={len(b['slipped'])} "
              f"deferred={len(b['deferred'])} cancelled={len(b['cancelled'])} "
              f"total={len(items)}")
    else:
        out = cycle_dir / "RETRO-PREVIEW.md"
        out.write_text(text)
        b = classify(items)
        print(f"cycle:    {cycle.id} (state={cycle.state} — preview only)")
        print(f"preview:  {out}")
        print(f"summary:  landed={len(b['landed'])} slipped={len(b['slipped'])} "
              f"deferred={len(b['deferred'])} cancelled={len(b['cancelled'])} "
              f"total={len(items)}")
        print("DRY-RUN — re-run with --apply to close")
    return 0


if __name__ == "__main__":
    sys.exit(main())
