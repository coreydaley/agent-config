#!/usr/bin/env python3
"""Cycle readiness / gap report. Identifies must-ship work items that
aren't in any Cycle, plus what's IN the target Cycle by state."""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path.home() / ".claude" / "lib"))
from plane_schema import (
    Cycle,
    Project,
    WorkItem,
    list_project_work_items,
    project_dir,
    resolve_org_repo,
)


MUST_SHIP_SEVERITIES = {"critical", "high"}
PRIORITY_ORDER = {"urgent": 0, "high": 1, "medium": 2, "low": 3, "none": 4}


def resolve_cycle(org: str, repo: str, requested: str | None) -> Cycle | None:
    cycles = Cycle.list(org, repo)
    if not cycles:
        return None
    if requested:
        for c in cycles:
            if c.id == requested:
                return c
        return None
    active = [c for c in cycles if c.state == "active"]
    if len(active) == 1:
        return active[0]
    return cycles[-1]


def render(cycle: Cycle, all_items: list[WorkItem], project: Project | None) -> str:
    org = cycle.workspace
    repo = cycle.project

    # Bucketize
    in_cycle: list[WorkItem] = []
    other_cycles: list[WorkItem] = []
    unassigned_must_ship: list[WorkItem] = []
    explicitly_deferred: list[WorkItem] = []

    for wi in all_items:
        must_ship = (wi.audit_severity or "") in MUST_SHIP_SEVERITIES
        if wi.state == "deferred":
            explicitly_deferred.append(wi)
            continue
        if wi.cycle == cycle.id:
            in_cycle.append(wi)
            continue
        if wi.cycle and wi.cycle != cycle.id:
            if must_ship:
                other_cycles.append(wi)
            continue
        # No cycle
        if must_ship and wi.state not in ("completed", "cancelled"):
            unassigned_must_ship.append(wi)

    # In-cycle state breakdown
    in_state: dict[str, int] = {}
    for wi in in_cycle:
        in_state[wi.state] = in_state.get(wi.state, 0) + 1

    # Sort helpers
    def sort_key(wi: WorkItem):
        return (PRIORITY_ORDER.get(wi.priority, 99), wi.id)

    project_name = project.name if project else repo
    lines = [
        f"# {project_name} — Readiness for {cycle.name}",
        "",
        f"_Auto-generated by `/plane-cycle-readiness`. Source: `{project_dir(org, repo) / 'work-items'}/`._",
        "",
        f"- **Cycle:** `{cycle.id}` · **State:** {cycle.state} · **Dates:** {cycle.start_date or '?'} → {cycle.end_date or '?'}",
        f"- **Total project work items:** {len(all_items)}",
        f"- **In this Cycle:** {len(in_cycle)}",
        f"- **Unassigned must-ship (alarm):** {len(unassigned_must_ship)}",
        f"- **In other Cycles (must-ship spread):** {len(other_cycles)}",
        f"- **Explicitly deferred:** {len(explicitly_deferred)}",
        "",
    ]

    # Alarm row first
    lines.append("## ⚠️ Unassigned must-ship items")
    lines.append("")
    if not unassigned_must_ship:
        lines.append("_None — all critical/high audit findings are either in a Cycle, completed, cancelled, or explicitly deferred._")
        lines.append("")
    else:
        lines.append(
            f"These {len(unassigned_must_ship)} item(s) have `audit_severity` ∈ "
            f"{{critical, high}}, are not in any Cycle, and are not deferred. "
            f"They are hiding outside the schedule — review and either assign "
            f"to this Cycle (`/plane-work-item-assign --cycle {cycle.id}`), "
            f"assign to a future Cycle, mark deferred with rationale "
            f"(`/plane-work-item-update --defer-to v0.x --defer-reason ...`), "
            f"or cancel."
        )
        lines.append("")
        lines += ["| ID | Severity | Priority | State | Title |",
                  "|---|---|---|---|---|"]
        for wi in sorted(unassigned_must_ship, key=sort_key):
            title = wi.title.replace("|", "\\|")[:80]
            lines.append(f"| {wi.id} | {wi.audit_severity} | {wi.priority} | "
                         f"{wi.state} | {title} |")
        lines.append("")

    # In-cycle
    lines.append(f"## In this Cycle ({len(in_cycle)})")
    lines.append("")
    if in_cycle:
        lines += ["| State | Count |", "|---|---:|"]
        for s in ("backlog", "unstarted", "started", "completed", "cancelled", "deferred"):
            n = in_state.get(s, 0)
            if n:
                lines.append(f"| {s} | {n} |")
        lines.append("")
        lines += ["| ID | State | Priority | Title |",
                  "|---|---|---|---|"]
        for wi in sorted(in_cycle, key=sort_key):
            title = wi.title.replace("|", "\\|")[:80]
            lines.append(f"| {wi.id} | {wi.state} | {wi.priority} | {title} |")
        lines.append("")
    else:
        lines.append("_No work items assigned to this Cycle._")
        lines.append("")

    # Other cycles must-ship spread
    if other_cycles:
        lines.append(f"## Must-ship items in other Cycles ({len(other_cycles)})")
        lines.append("")
        lines.append(
            "These are critical/high audit findings scheduled into a different "
            "Cycle. Confirm that's intentional (e.g. they belong in a future "
            "release, not this one)."
        )
        lines.append("")
        lines += ["| ID | Severity | Cycle | State | Title |",
                  "|---|---|---|---|---|"]
        for wi in sorted(other_cycles, key=sort_key):
            title = wi.title.replace("|", "\\|")[:80]
            lines.append(f"| {wi.id} | {wi.audit_severity} | {wi.cycle} | "
                         f"{wi.state} | {title} |")
        lines.append("")

    # Deferred
    if explicitly_deferred:
        lines.append(f"## Explicitly deferred ({len(explicitly_deferred)})")
        lines.append("")
        lines += ["| ID | Severity | Defer to | Reason | Title |",
                  "|---|---|---|---|---|"]
        for wi in sorted(explicitly_deferred, key=sort_key):
            reason = (wi.deferral_reason or "")[:80].replace("|", "\\|").replace("\n", " ")
            title = wi.title.replace("|", "\\|")[:60]
            lines.append(f"| {wi.id} | {wi.audit_severity or '-'} | "
                         f"{wi.deferral_target or '?'} | {reason} | {title} |")
        lines.append("")

    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--scope", default=".", help="Project root.")
    ap.add_argument("--cycle", help="Cycle id (defaults to active/latest).")
    ap.add_argument("--stdout", action="store_true",
                    help="Print to stdout instead of writing READINESS.md.")
    args = ap.parse_args()

    project_cwd = Path(args.scope).resolve()
    org, repo = resolve_org_repo(project_cwd)

    cycle = resolve_cycle(org, repo, args.cycle)
    if cycle is None:
        if args.cycle:
            print(f"error: no Cycle with id {args.cycle!r} in {org}/{repo}",
                  file=sys.stderr)
        else:
            print(f"error: no Cycles exist in {org}/{repo}/cycles/",
                  file=sys.stderr)
        return 1

    # Load all work items
    all_items: list[WorkItem] = []
    for p in list_project_work_items(org, repo):
        try:
            all_items.append(WorkItem.load(p))
        except Exception:
            continue

    project = Project.load(org, repo)
    text = render(cycle, all_items, project)

    if args.stdout:
        print(text)
    else:
        out = Cycle.dir_for(org, repo, cycle.id) / "READINESS.md"
        out.write_text(text)
        print(f"cycle:    {cycle.id}")
        print(f"output:   {out}")

    # Surface the gap count to stdout regardless of mode
    gaps = sum(1 for wi in all_items
               if (wi.audit_severity or "") in MUST_SHIP_SEVERITIES
               and not wi.cycle
               and wi.state not in ("completed", "cancelled", "deferred"))
    if gaps:
        print(f"⚠️  {gaps} unassigned must-ship item(s)")
    else:
        print("✅ no unassigned must-ship items")
    return 0


if __name__ == "__main__":
    sys.exit(main())
