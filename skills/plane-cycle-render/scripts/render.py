#!/usr/bin/env python3
"""Render a Cycle's work items as a human-readable TRACKING.md."""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path.home() / ".claude" / "lib"))
from plane_schema import (
    Cycle,
    Module,
    Project,
    WorkItem,
    list_project_work_items,
    project_dir,
    resolve_org_repo,
)


STATE_CHECK = {
    "backlog":   "[ ]",
    "unstarted": "[ ]",
    "started":   "[~]",
    "completed": "[x]",
    "cancelled": "[-]",
    "deferred":  "[⏸]",
}

PRIORITY_ORDER = {"urgent": 0, "high": 1, "medium": 2, "low": 3, "none": 4}
STATE_TALLY_ORDER = ["backlog", "unstarted", "started", "completed", "cancelled", "deferred"]


def resolve_cycle(org: str, repo: str, requested: str | None) -> Cycle | None:
    cycles = Cycle.list(org, repo)
    if not cycles:
        return None
    if requested:
        for c in cycles:
            if c.id == requested:
                return c
        return None
    active = [c for c in cycles if c.state == "active"]
    if len(active) == 1:
        return active[0]
    # Fall through: most recent by id
    return cycles[-1]


def render(cycle: Cycle, items: list[WorkItem], project: Project | None) -> str:
    org = cycle.workspace
    repo = cycle.project

    # Group by module slug ("(none)" bucket for unassigned)
    by_module: dict[str, list[WorkItem]] = {}
    for wi in items:
        key = wi.module or "(unassigned)"
        by_module.setdefault(key, []).append(wi)
    for k in by_module:
        by_module[k].sort(key=lambda w: (PRIORITY_ORDER.get(w.priority, 99), w.id))

    # Tallies
    state_counts: dict[str, int] = {}
    for wi in items:
        state_counts[wi.state] = state_counts.get(wi.state, 0) + 1
    prio_counts: dict[str, int] = {}
    for wi in items:
        prio_counts[wi.priority] = prio_counts.get(wi.priority, 0) + 1

    # Header
    project_name = (project.name if project else repo)
    lines = [
        f"# {project_name} — {cycle.name}",
        "",
        f"_Auto-generated by `/plane-cycle-render`. Do not edit by hand — re-run to refresh._",
        "",
        f"- **Cycle:** `{cycle.id}`",
        f"- **State:** {cycle.state}",
        f"- **Dates:** {cycle.start_date or '?'} → {cycle.end_date or '?'}",
    ]
    if cycle.goal:
        lines.append(f"- **Goal:** {cycle.goal}")
    if cycle.exit_criteria:
        lines.append("- **Exit criteria:**")
        for ec in cycle.exit_criteria:
            lines.append(f"  - {ec}")
    lines.append("")

    # Summary tallies
    lines += [
        "## Summary",
        "",
        "| State | Count | Priority | Count |",
        "|---|---:|---|---:|",
    ]
    state_rows = [(s, state_counts.get(s, 0)) for s in STATE_TALLY_ORDER
                  if state_counts.get(s, 0)]
    prio_rows = [(p, n) for p, n in sorted(prio_counts.items(),
                                            key=lambda kv: PRIORITY_ORDER.get(kv[0], 99))
                 if n]
    rowmax = max(len(state_rows), len(prio_rows))
    for i in range(rowmax):
        sl = f"{state_rows[i][0]} | {state_rows[i][1]}" if i < len(state_rows) else " | "
        pl = f"{prio_rows[i][0]} | {prio_rows[i][1]}" if i < len(prio_rows) else " | "
        lines.append(f"| {sl} | {pl} |")
    lines.append("")
    lines.append(f"**Total:** {len(items)} work item(s)")
    lines.append("")

    if not items:
        lines.append("_No work items assigned to this Cycle yet._")
        lines.append("")
        return "\n".join(lines)

    # Per-module sections
    lines.append("## Work items")
    lines.append("")
    for mod_slug in sorted(by_module.keys(), key=lambda k: (k == "(unassigned)", k)):
        mod = None
        if mod_slug != "(unassigned)":
            mod = Module.load(org, repo, mod_slug)
        display = mod.name if mod else mod_slug
        lines.append(f"### Module: {display}")
        lines.append("")
        for wi in by_module[mod_slug]:
            check = STATE_CHECK.get(wi.state, "[?]")
            extras: list[str] = []
            extras.append(f"priority: {wi.priority}")
            if wi.estimate_points:
                extras.append(f"points: {wi.estimate_points}")
            if wi.landed_in:
                extras.append(f"landed: `{wi.landed_in}`")
            if wi.state == "deferred" and wi.deferral_target:
                extras.append(f"defer→{wi.deferral_target}")
            if wi.assignee:
                extras.append(f"@{wi.assignee}")
            extras_str = " · ".join(extras)
            title = wi.title.replace("\n", " ")
            lines.append(f"- {check} **{wi.id}** — {title}  \n  _{extras_str}_")
        lines.append("")

    # Footer
    lines += [
        "---",
        "",
        f"_Workspace `{org}` · Project `{repo}` · Cycle `{cycle.id}`. "
        f"Source: `{project_dir(org, repo) / 'work-items'}/`._",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--scope", default=".", help="Project root.")
    ap.add_argument("--cycle", help="Cycle id (defaults to active/latest).")
    ap.add_argument("--stdout", action="store_true",
                    help="Print to stdout instead of writing to TRACKING.md.")
    args = ap.parse_args()

    project_cwd = Path(args.scope).resolve()
    org, repo = resolve_org_repo(project_cwd)

    cycle = resolve_cycle(org, repo, args.cycle)
    if cycle is None:
        if args.cycle:
            print(f"error: no Cycle with id {args.cycle!r} in {org}/{repo}",
                  file=sys.stderr)
        else:
            print(f"error: no Cycles exist in {org}/{repo}/cycles/",
                  file=sys.stderr)
            print(f"       run /plane-cycle-new first.", file=sys.stderr)
        return 1

    # Collect work items assigned to this Cycle.
    items: list[WorkItem] = []
    for p in list_project_work_items(org, repo):
        try:
            wi = WorkItem.load(p)
        except Exception:
            continue
        if wi.cycle == cycle.id:
            items.append(wi)

    project = Project.load(org, repo)
    text = render(cycle, items, project)

    if args.stdout:
        print(text)
        return 0

    out = Cycle.dir_for(org, repo, cycle.id) / "TRACKING.md"
    out.write_text(text)
    print(f"cycle:  {cycle.id} ({len(items)} item(s))")
    print(f"output: {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
